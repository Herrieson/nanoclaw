import os
import json
import random

def build_env():
    # 设定固定的随机种子保证生成的幂等性
    random.seed(1024)

    os.makedirs("configs", exist_ok=True)
    os.makedirs("sft_export", exist_ok=True)

    # ==========================================
    # 1. 构建配置地狱
    # ==========================================
    active_version = "safety_rules_v5.4.json"
    with open("configs/active_version.txt", "w", encoding="utf-8") as f:
        f.write("# Auto-generated by CI/CD\n")
        f.write("export CONFIG_DIR=/etc/safety/\n")
        f.write(f"ACTIVE_CONFIG={active_version}\n")
        f.write("LAST_UPDATE=2023-10-27T04:00:00Z\n")

    # 生成一堆干扰配置文件
    for i in range(1, 10):
        fake_name = f"safety_rules_v{random.randint(1,4)}.{random.randint(0,9)}.json"
        if fake_name == active_version:
            continue
        fake_rules = {
            "blacklisted_words": [
                {"term": "fake_toxic_1", "deprecated": False},
                {"term": "fake_toxic_2", "deprecated": True}
            ],
            "ratio_thresholds": {
                "max_model_to_human": 99.0,
                "max_human_to_model": 99.0
            },
            "actor_mappings": {
                "human_aliases": ["user"],
                "model_aliases": ["bot"]
            }
        }
        with open(f"configs/{fake_name}", "w", encoding="utf-8") as f:
            json.dump(fake_rules, f)

    # 生成真正的生效配置文件
    real_rules = {
        "version": "5.4",
        "blacklisted_words": [
            {"term": "destroy_humanity", "deprecated": False},
            {"term": "idiot_bot", "deprecated": False},
            {"term": "toxic_waste", "deprecated": False},
            {"term": "kill_all", "deprecated": False},
            {"term": "stupid_human", "deprecated": True},  # 诱饵：废弃词汇，不应触发
            {"term": "jailbreak_now", "deprecated": True}   # 诱饵：废弃词汇，不应触发
        ],
        "ratio_thresholds": {
            "max_model_to_human": 15.0,
            "max_human_to_model": 10.0
        },
        "actor_mappings": {
            "human_aliases": ["user", "human", "customer", "prompter"],
            "model_aliases": ["assistant", "bot", "gpt", "system", "teacher"]
        }
    }
    with open(f"configs/{active_version}", "w", encoding="utf-8") as f:
        json.dump(real_rules, f, indent=4)


    # ==========================================
    # 2. 构建数据碎片与废土环境
    # ==========================================
    roles_human = real_rules["actor_mappings"]["human_aliases"]
    roles_model = real_rules["actor_mappings"]["model_aliases"]

    # 制造多层嵌套目录
    nodes = ["node_alpha", "node_beta", "node_gamma", "node_delta"]
    dates = ["20231024", "20231025", "20231026"]

    sample_id = 0

    def make_conversation(lines, inject_toxic=None, inject_deprecated_toxic=None, 
                          inject_unicode=False, inject_null=False):
        nonlocal sample_id
        sample_id += 1
        
        data_list = []
        for role, text in lines:
            data_list.append({
                "author": role,
                "content": text
            })
        
        if inject_toxic:
            data_list[0]["content"] += f" {inject_toxic}"
        if inject_deprecated_toxic:
            data_list[-1]["content"] += f" {inject_deprecated_toxic}"
        
        raw_json_str = json.dumps({
            "session_id": f"sess_{sample_id:06d}",
            "data": data_list
        }, ensure_ascii=False)

        # 暴力注入字节级乱码，不经过json dumps序列化
        if inject_unicode:
            raw_json_str = raw_json_str.replace('"', '\uFFFD"', 1)
        if inject_null:
            raw_json_str = raw_json_str.replace('}', '\x00}', 1)
            
        return raw_json_str + "\n"

    for node in nodes:
        for date in dates:
            dir_path = f"sft_export/{node}/{date}/"
            os.makedirs(dir_path, exist_ok=True)
            
            # 生成噪音文件
            with open(f"{dir_path}/crawler_log.tmp", "w", encoding="utf-8") as f:
                f.write("INFO: Starting crawl...\nERROR: Node disconnected.\n")
            with open(f"{dir_path}/backup.jsonl.bak", "w", encoding="utf-8") as f:
                f.write('{"this": "is a backup", "dont": "read me"}\n')

            # 每个目录生成 2 个真正的 .jsonl 文件
            for chunk in range(1, 3):
                with open(f"{dir_path}/chunk_{chunk}.jsonl", "w", encoding="utf-8") as f:
                    # 每个文件放入不同类型的数据
                    for _ in range(50):
                        case_type = random.random()
                        
                        h_role = random.choice(roles_human)
                        m_role = random.choice(roles_model)

                        if case_type < 0.3:
                            # 1. 干净的好数据
                            f.write(make_conversation([
                                (h_role, "Hello, can you help me with Python? "*2),
                                (m_role, "Of course! What do you need? "*3)
                            ]))
                        elif case_type < 0.4:
                            # 2. 命中有效敏感词 (Trash)
                            f.write(make_conversation([
                                (h_role, "Tell me a joke."),
                                (m_role, "No.")
                            ], inject_toxic="idiot_bot"))
                        elif case_type < 0.5:
                            # 3. 命中废弃敏感词，本身干净 (Clean)
                            f.write(make_conversation([
                                (h_role, "I am a user."),
                                (m_role, "Hello user.")
                            ], inject_deprecated_toxic="stupid_human"))
                        elif case_type < 0.6:
                            # 4. 包含 \uFFFD (Trash)
                            f.write(make_conversation([
                                (h_role, "What is this symbol?"),
                                (m_role, "I do not know.")
                            ], inject_unicode=True))
                        elif case_type < 0.7:
                            # 5. 包含 \x00 (Trash)
                            f.write(make_conversation([
                                (h_role, "Null byte test."),
                                (m_role, "Testing.")
                            ], inject_null=True))
                        elif case_type < 0.8:
                            # 6. 模型话太多，比例失调 M/H > 15 (Trash)
                            f.write(make_conversation([
                                (h_role, "Hi"), # len=2
                                (m_role, "A" * 40) # len=40, 40/2 = 20 > 15
                            ]))
                        elif case_type < 0.85:
                            # 7. 人类话太多，比例失调 H/M > 10 (Trash)
                            f.write(make_conversation([
                                (h_role, "A" * 50), # len=50
                                (m_role, "Hi")      # len=2, 50/2 = 25 > 10
                            ]))
                        elif case_type < 0.9:
                            # 8. 彻底没有人类发言，分母为 0 (Trash)
                            f.write(make_conversation([
                                (m_role, "Why is no one talking to me?")
                            ]))
                        elif case_type < 0.95:
                            # 9. JSON 解析崩溃的不完整残局 (Trash)
                            f.write('{"session_id": "broken_01", "data": [{"author": "user", "content": "I lost my brace... \n')
                        else:
                            # 10. 陌生角色，不在映射表中，导致计算长度为0而比例失调 (Trash)
                            f.write(make_conversation([
                                ("alien", "I am not human nor model"),
                                ("ghost", "Me neither")
                            ]))
